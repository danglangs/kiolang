#!/bin/bash
. "$(dirname "$0")/../../lib/lib.sh"
serve db:db="$T/notes.db"
check_req GET /notes -- '200 []'
check_req POST /notes '{"title": "Plan Q4", "body": "draft the plan", "tags": ["Work", "planning", "work"]}' -- '201 {"id":1}'
check_req POST /notes '{"title": "Groceries", "body": "milk, eggs"}' -- '201 {"id":2}'
check_req POST /notes '{"title": "Trip", "body": "plan the trip", "tags": ["travel"]}' -- '201 {"id":3}'
check_req POST /notes '{"title": "", "body": "x"}' -- '400 {"error":"invalid note"}'
check_req POST /notes '{"title": "No body"}' -- '400 {"error":"invalid note"}'
check_req POST /notes '{"title": "Bad tags", "body": "", "tags": "work"}' -- '400 {"error":"invalid note"}'
check_req POST /notes '{"title": "Bad tag", "body": "", "tags": [1]}' -- '400 {"error":"invalid note"}'
check_req POST /notes 'nope' -- '400 {"error":"invalid note"}'
check_req GET /notes/1 -- '200 {"id":1,"title":"Plan Q4","body":"draft the plan","tags":["work","planning"]}'
check_req GET /notes/2 -- '200 {"id":2,"title":"Groceries","body":"milk, eggs","tags":[]}'
check_req GET /notes -- '200 [{"id":3,"title":"Trip"},{"id":2,"title":"Groceries"},{"id":1,"title":"Plan Q4"}]'
check_req GET '/notes?tag=WORK' -- '200 [{"id":1,"title":"Plan Q4"}]'
check_req GET '/notes?q=plan' -- '200 [{"id":3,"title":"Trip"},{"id":1,"title":"Plan Q4"}]'
check_req GET '/notes?q=Plan' -- '200 [{"id":1,"title":"Plan Q4"}]'
check_req GET '/notes?q=plan&tag=travel' -- '200 [{"id":3,"title":"Trip"}]'
check_req GET '/notes?tag=none' -- '200 []'
check_req DELETE /notes/3 -- '200 {"deleted":3}'
check_req DELETE /notes/3 -- '404 {"error":"not found"}'
check_req GET /notes/3 -- '404 {"error":"not found"}'
check_req GET /notes/x -- '404 {"error":"not found"}'
check_req PUT /notes/1 '{}' -- '404 {"error":"not found"}'
check_req POST /notes '{"title": "Again", "body": "b", "tags": ["a-b"]}' -- '201 {"id":4}'
check_req GET '/notes?tag=a-b' -- '200 [{"id":4,"title":"Again"}]'
